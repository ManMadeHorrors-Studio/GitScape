class ModulesTest {

    @Test
    fun `DomainModule repository provider creates implementation with supplied dependencies`() {
        val api = mockk<GitHubApis>()
        val cache = mockk<GitHubReadMeCache>()

        val repository = RepositoryModule.provideGitHubRepository(api, cache)

        assertTrue(repository is GitHubRepositoryImpl)
        assertSame(api, repository.privateField("api"))
        assertSame(cache, repository.privateField("readMeCache"))
    }

    @Test
    fun `DomainModule use case providers create the expected types`() {
        val repository = mockk<GitHubRepository>()

        assertTrue(UseCaseModule.provideGetGitHubRepoListUseCase(repository) is GetGitHubRepoListUseCase)
        assertTrue(UseCaseModule.provideGetGitHubUserUseCase(repository) is GetGitHubUserUseCase)
        assertTrue(UseCaseModule.provideGetGitHubReadMeUseCase(repository) is GetGitHubReadMeUseCase)
    }

    @Test
    fun `DomainModule use case providers wire repository and delegate`() {
        val repository = mockk<GitHubRepository>(relaxed = true)
        val repoListUseCase = UseCaseModule.provideGetGitHubRepoListUseCase(repository)
        val userUseCase = UseCaseModule.provideGetGitHubUserUseCase(repository)
        val readMeUseCase = UseCaseModule.provideGetGitHubReadMeUseCase(repository)

        assertSame(repository, repoListUseCase.privateField("repository"))
        assertSame(repository, userUseCase.privateField("repository"))
        assertSame(repository, readMeUseCase.privateField("repository"))
    }

    @Test
    fun `NetworkModule provides auth interceptor and client with expected interceptors`() {
        val authInterceptor = NetworkModule.provideGitHubAuthInterceptor()
        val client = NetworkModule.provideOkHttpClient(authInterceptor)

        assertNotNull(authInterceptor)
        assertTrue(client.interceptors.contains(loggingInterceptor))
        assertTrue(client.interceptors.any { it is GitHubAuthInterceptor })
    }

    @Test
    fun `NetworkModule creates GitHub API with the expected base URL without network`() {
        val client = OkHttpClient.Builder().build()
        val api = NetworkModule.provideGitHubApi(client)

        assertNotNull(api)
        val retrofit = Proxy.getInvocationHandler(api).findFieldOfType(Retrofit::class.java) as? Retrofit
        assertNotNull(retrofit)
        assertEquals("https://$GITHUB_API_BASE_PATH/", retrofit!!.baseUrl().toString())
    }

    @Test
    fun `DatabaseModule DAO providers return DAO instances from mocked database`() {
        val database = mockk<AppDatabase>()
        val settingsDao = mockk<SettingsDao>()
        val gitHubDao = mockk<GitHubDao>()
        io.mockk.every { database.getSettingsDao() } returns settingsDao
        io.mockk.every { database.getGitHubDao() } returns gitHubDao

        assertSame(settingsDao, DatabaseModule.provideSettingsDao(database))
        assertSame(gitHubDao, DatabaseModule.provideGitHubDao(database))
    }

    /** SettingsModule/LocalGitHubModule @Binds methods are generated by Hilt and are not directly invocable. */
    @Test
    fun `abstract bind providers are intentionally not tested`() {
        assertTrue(true)
    }

    private fun Any.findFieldOfType(expectedType: Class<*>): Any? {
        var type: Class<*>? = javaClass
        while (type != null) {
            type.declaredFields.forEach { field ->
                if (expectedType.isAssignableFrom(field.type)) {
                    field.isAccessible = true
                    return field.get(this)
                }
            }
            type = type.superclass
        }
        return null
    }

    private fun Any.privateField(name: String): Any? {
        var type: Class<*>? = javaClass
        while (type != null) {
            try {
                return type.getDeclaredField(name).apply { isAccessible = true }.get(this)
            } catch (_: NoSuchFieldException) {
                type = type.superclass
            }
        }
        error("Field $name not found on ${javaClass.name}")
    }
}
